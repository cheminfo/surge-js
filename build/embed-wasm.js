// Reads the built .wasm and the Emscripten JS glue and rewrites them into
// TypeScript modules committed under src/, so that installing the package
// needs neither a compiler nor a network fetch.
//
// The .wasm is gzipped and base64-encoded; the glue is turned into an ES
// module exposing the factory as its default export.

import { Buffer } from 'node:buffer';
import { readFileSync, writeFileSync } from 'node:fs';
import { argv, stdout } from 'node:process';

const args = parseArgs();

const wasm = new Uint8Array(readFileSync(args.wasm));
const gzipped = await gzip(wasm);
const base64 = Buffer.from(gzipped).toString('base64');

writeFileSync(
  args['out-data'],
  `${header()}
/** The surge WebAssembly module, gzip-compressed then base64-encoded. */
export const wasmBase64 =
  '${base64}';
`,
);

writeFileSync(args['out-glue'], glueModule(readFileSync(args.glue, 'utf8')));

writeFileSync(
  args['out-version'],
  `${header()}
/** Version of the surge C program the embedded WebAssembly was compiled from. */
export const SURGE_VERSION = '${args['surge-version']}';

/** Version of the nauty library surge is built on. */
export const NAUTY_VERSION = '${args['nauty-version']}';

/** Version of the Emscripten toolchain that compiled it. */
export const EMSCRIPTEN_VERSION = '${args['emscripten-version']}';
`,
);

stdout.write(
  `   wasm ${wasm.length} bytes -> ${gzipped.length} gzipped -> ${base64.length} base64\n`,
);

function header() {
  return `// This file is generated by build/embed-wasm.js. Do not edit by hand.
// Run \`npm run build-wasm\` to regenerate it.
`;
}

/**
 * Wrap the Emscripten output as an ES module. `-sEXPORT_ES6` already emits
 * one, so the only thing to do is silence the linters on generated code.
 * @param {string} source - The glue Emscripten wrote.
 * @returns {string} The module written to src/wasm/glue.ts.
 */
function glueModule(source) {
  return `${header()}
// Emscripten glue for the surge WebAssembly module. The factory takes an
// options bag including \`wasmBinary\`, so the bytes are handed over directly
// and nothing is ever fetched.

/* eslint-disable */
// @ts-nocheck

${source}
`;
}

/**
 * Compress with the stream API, so nothing here needs node:zlib.
 * @param {Uint8Array} bytes - What to compress.
 * @returns {Promise<Uint8Array>} The gzipped bytes.
 */
async function gzip(bytes) {
  const stream = new Blob([bytes])
    .stream()
    .pipeThrough(new CompressionStream('gzip'));
  return new Uint8Array(await new Response(stream).arrayBuffer());
}

function parseArgs() {
  const parsed = {};
  for (let index = 2; index < argv.length; index += 2) {
    const key = argv[index];
    const value = argv[index + 1];
    if (!key?.startsWith('--') || value === undefined) {
      throw new Error(`Bad argument: ${key}`);
    }
    parsed[key.slice(2)] = value;
  }
  for (const required of [
    'wasm',
    'glue',
    'out-data',
    'out-glue',
    'out-version',
    'surge-version',
    'nauty-version',
    'emscripten-version',
  ]) {
    if (parsed[required] === undefined) {
      throw new Error(`Missing --${required}`);
    }
  }
  return parsed;
}
